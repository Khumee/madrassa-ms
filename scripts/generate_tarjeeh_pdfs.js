    <p><strong>ردِ صدر الشریعہؒ:</strong> شریعتِ مطہرہ میں علت کا مدار اس کے شرعی اعتبار، ثبوت اور تاثیر پر ہے۔ اجزاء کی کمی یا زیادتی سے شریعت میں ترجیح کا کوئی تعلق نہیں۔</p>
